import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

DATA_URL = "https://raw.githubusercontent.com/owid/covid-19-data/master/public/data/owid-covid-data.csv"
USE_PUBLIC_DATA = True  # Change to False to use the included synthetic demo CSV.

if USE_PUBLIC_DATA:
    try:
        raw = pd.read_csv(DATA_URL)
        print("Loaded official OWID data:", raw.shape)
    except Exception as e:
        print("Could not download public data:", e)
        print("Using included synthetic demonstration data instead.")
        raw = pd.read_csv("covid_demo_raw.csv")
else:
    raw = pd.read_csv("covid_demo_raw.csv")

# Select countries and relevant fields
countries = ["India", "United States", "Brazil", "United Kingdom", "Germany", "Japan"]
cols = ["location", "date", "population", "new_cases", "new_deaths",
        "people_fully_vaccinated_per_hundred"]
df = raw.loc[raw["location"].isin(countries), cols].copy()
df["date"] = pd.to_datetime(df["date"], errors="coerce")
df = df.dropna(subset=["date", "population"]).sort_values(["location", "date"])
df = df.drop_duplicates(subset=["location", "date"])
print("Rows after filtering and duplicate removal:", len(df))
print("Missing values before treatment:\n", df.isna().sum())

# Handle missing daily case/death values using a within-country 7-day rolling median.
for col in ["new_cases", "new_deaths"]:
    df[col] = df.groupby("location")[col].transform(
        lambda s: s.fillna(s.rolling(7, min_periods=1).median())
    )
df["new_cases"] = df["new_cases"].clip(lower=0)
df["new_deaths"] = df["new_deaths"].clip(lower=0)

# Derived metrics
df["new_cases_7day_avg"] = df.groupby("location")["new_cases"].transform(
    lambda s: s.rolling(7, min_periods=1).mean()
)
df["new_deaths_7day_avg"] = df.groupby("location")["new_deaths"].transform(
    lambda s: s.rolling(7, min_periods=1).mean()
)
df["cases_per_million"] = df["new_cases"] / df["population"] * 1_000_000
df["deaths_per_million"] = df["new_deaths"] / df["population"] * 1_000_000
df["case_fatality_rate_pct"] = np.where(
    df["new_cases"] > 0, df["new_deaths"] / df["new_cases"] * 100, np.nan
)
print("Missing values after treatment:\n", df.isna().sum())

# Country-level summary
summary = df.groupby("location").agg(
    avg_cases_per_million=("cases_per_million", "mean"),
    avg_deaths_per_million=("deaths_per_million", "mean"),
    total_cases=("new_cases", "sum"),
    total_deaths=("new_deaths", "sum"),
    latest_vaccination_pct=("people_fully_vaccinated_per_hundred", "last")
).reset_index()
summary["case_fatality_rate_pct"] = summary["total_deaths"] / summary["total_cases"] * 100
summary

# Trend chart
plt.figure(figsize=(12, 5))
for country, group in df.groupby("location"):
    plt.plot(group["date"], group["new_cases_7day_avg"], label=country)
plt.title("Daily COVID-19 cases — 7-day moving average")
plt.xlabel("Date"); plt.ylabel("Cases"); plt.legend()
plt.tight_layout(); plt.show()

# Fair country comparison: average daily cases per million
plot_data = summary.sort_values("avg_cases_per_million")
plt.figure(figsize=(9, 5))
plt.barh(plot_data["location"], plot_data["avg_cases_per_million"])
plt.xlabel("Average daily cases per million")
plt.title("Average daily cases per million by country")
plt.tight_layout(); plt.show()

# Vaccination and death-rate relationship (descriptive, not causal)
plt.figure(figsize=(8, 5))
plt.scatter(df["people_fully_vaccinated_per_hundred"], df["deaths_per_million"], alpha=0.25)
plt.xlabel("Fully vaccinated (% population)")
plt.ylabel("Daily deaths per million")
plt.title("Vaccination coverage vs daily deaths per million")
plt.tight_layout(); plt.show()

# Export cleaned data and summary
df.to_csv("covid_cleaned_metrics.csv", index=False)
summary.to_csv("country_summary.csv", index=False)
print("Saved covid_cleaned_metrics.csv and country_summary.csv")